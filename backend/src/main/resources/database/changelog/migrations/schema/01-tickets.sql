--comment: create the ticket table
CREATE TABLE ticket_tracker.tickets
(
    id          BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    created_at  TIMESTAMPTZ  NOT NULL,
    description TEXT,
    priority    VARCHAR(50)  NOT NULL,
    status      VARCHAR(50)  NOT NULL,
    title       VARCHAR(255) NOT NULL,

    CONSTRAINT pk_tickets PRIMARY KEY (id),
    CONSTRAINT ck_tickets_priority CHECK (priority IN ('HIGH', 'LOW', 'MEDIUM')),
    CONSTRAINT ck_tickets_status CHECK (status IN ('CLOSED', 'IN_PROGRESS', 'OPEN')),
    CONSTRAINT ck_tickets_title CHECK (title ~ '\S')
);

--comment: create indexes for the ticket table
CREATE INDEX idx_tickets_created_at ON ticket_tracker.tickets (created_at);
CREATE INDEX idx_tickets_status ON ticket_tracker.tickets (status);

--comment: add table and column comments for ticket
COMMENT ON TABLE ticket_tracker.tickets IS 'One record per support ticket. Owns title, description, status, and priority.';
COMMENT ON COLUMN ticket_tracker.tickets.id IS 'Primary key, bigint identity, assigned at record creation.';
COMMENT ON COLUMN ticket_tracker.tickets.created_at IS 'UTC timestamp at which the ticket was created.';
COMMENT ON COLUMN ticket_tracker.tickets.description IS 'Optional detailed description of the ticket. Null when the author supplies none.';
COMMENT ON COLUMN ticket_tracker.tickets.priority IS 'Ticket priority: LOW, MEDIUM, or HIGH.';
COMMENT ON COLUMN ticket_tracker.tickets.status IS 'Ticket status: OPEN, IN_PROGRESS, or CLOSED. Transitions are enforced by the application.';
COMMENT ON COLUMN ticket_tracker.tickets.title IS 'Short title of the ticket. Holds at least one non-whitespace character and at most 255 characters.';